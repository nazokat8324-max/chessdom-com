  const put = (arr, v) => { if (!Array.isArray(arr) || v == null) return; while (arr.length < IDX) arr.push(arr[1] || ''); arr[IDX] = v; };
  (window.LibraryArticles || []).forEach((a) => {
    const t = KK.articles[a.id];
    if (!t) return;
    put(a.title, t.title);
    put(a.lead, t.lead);
    (a.points || []).forEach((p, i) => put(p, t.points && t.points[i]));
    if (a.example && t.caption) put(a.example.caption, t.caption);
  });
  const D = window.LibraryData || {};
  (D.GAMES || []).forEach((g) => { const t = KK.games[g.id]; if (t) { put(g.title, t.title); put(g.story, t.story); } });
  (D.BOOKS || []).forEach((b) => { const t = KK.books[b.id]; if (t) put(b.desc, t); });
